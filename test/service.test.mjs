import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'arena-service-'));
process.env.HOME = tmp;
process.env.ARENA_BRIDGE_HOME = path.join(tmp, 'config');
process.env.ARENA_BRIDGE_APP = path.join(tmp, 'Arena & Bridge.app');
const bin = path.join(tmp, 'bin');
fs.mkdirSync(bin);
const calls = path.join(tmp, 'calls');
fs.writeFileSync(path.join(bin, 'launchctl'), `#!${process.execPath}\nrequire('fs').appendFileSync(${JSON.stringify(calls)}, JSON.stringify(process.argv.slice(2))+'\\n');\nif (process.env.FAIL_SUBMIT && process.argv[2]==='submit') process.exit(1);\n`, { mode: 0o755 });
process.env.PATH = `${bin}:${process.env.PATH}`;
const m = await import('../src/service.mjs');
try {
  const options = { bin: 'ngrok', domain: 'test.ngrok-free.dev', port: 9999 };
  let r = m.serviceInstall(options);
  assert.equal(r.scheduled, true);
  assert.ok(m.plistPath().startsWith(tmp));
  let xml = fs.readFileSync(r.plist, 'utf8');
  assert.ok(xml.includes(`<string>${m.runnerPath()}</string>`));
  assert.ok(xml.includes('<key>KeepAlive</key><true/>'));
  const helper = path.join(process.env.ARENA_BRIDGE_APP, 'Contents/Helpers/arena-bridge-agent');
  fs.mkdirSync(path.dirname(helper), { recursive: true });
  fs.writeFileSync(path.join(process.env.ARENA_BRIDGE_APP, 'Contents/Info.plist'), '<plist/>');
  fs.writeFileSync(helper, '#!/bin/sh\n', { mode: 0o755 });
  r = m.serviceInstall(options);
  xml = fs.readFileSync(r.plist, 'utf8');
  assert.ok(xml.includes('Arena &amp; Bridge.app'));
  assert.deepEqual(m.programArguments(options).slice(3), ['tunnel', '--bin', 'ngrok', '--domain', options.domain, '--port', '9999']);
  const log = fs.readFileSync(calls, 'utf8').trim().split('\n').map(JSON.parse);
  assert.equal(log.length, 2);
  assert.ok(log.every(a => a[0] === 'submit'), 'installer must not stop its own parent');
  const script = log[1][log[1].indexOf('/bin/sh') + 1];
  assert.equal(fs.readFileSync(script, 'utf8'), m.reloadScript);
  process.env.FAIL_SUBMIT = '1';
  assert.equal(m.serviceInstall(options).ok, false);
  delete process.env.FAIL_SUBMIT;
  m.serviceUninstall();
  assert.equal(fs.existsSync(r.plist), false);
  console.log('PASS: service install/reinstall, actual plist, helper/fallback, queued reload, errors, uninstall');
} finally { fs.rmSync(tmp, { recursive: true, force: true }); }
